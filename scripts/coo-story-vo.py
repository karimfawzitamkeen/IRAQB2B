def main():
    root = os.path.join(os.path.dirname(__file__), '..')
    src = open(os.path.join(root, 'src', 'coo-story', 'theme.ts'), encoding='utf-8').read()
    cues = re.findall(r"\{a: (\d+), b: (\d+), text: '([^']*)'\}", src)
    def ts(fr):
        ms = round(int(fr) / 30 * 1000)
        return f"{ms // 3600000:02}:{ms // 60000 % 60:02}:{ms // 1000 % 60:02},{ms % 1000:03}"
    out = os.path.join(root, 'out', 'coo-story-vo.srt')
    with open(out, 'w', encoding='utf-8') as f:
        for i, (a, b, t) in enumerate(cues, 1):
            f.write(f"{i}\n{ts(a)} --> {ts(b)}\n{t}\n\n")
    print('wrote', out, len(cues), 'cues')
    assert len(LINES) == len(cues)
    sheet = os.path.join(root, 'out', 'coo-story-vo-narrator.txt')
    with open(sheet, 'w', encoding='utf-8') as f:
        f.write('من رحلة طويلة إلى خدمة رقمية — نص التعليق الصوتي\n')
        f.write('المدة الكلية 1:58 · 18 مقطعاً · سرعة القراءة المقترحة نحو 2.3–2.5 كلمة في الثانية\n')
        f.write('يبدأ كل مقطع عند وقت البداية، وينتهي قبل وقت النهاية. النص مشكول للنطق الفصيح الصحيح.\n\n')
        for i, ((a, b, _), line) in enumerate(zip(cues, LINES), 1):
            f.write(f"{i:02d}   {ts(a)[3:8]} – {ts(b)[3:8]}   ({(int(b) - int(a)) / 30:.1f} ث، {len(line.split())} كلمة)\n{line}\n\n")
    print('wrote', sheet)


if __name__ == '__main__':
    main()
